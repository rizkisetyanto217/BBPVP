// 3. Compound Assignment Operator
let x = 20;
console.log("Nilai awal x:", x);

// Tambah lalu simpan
x += 5;
console.log("Setelah x += 5:", x);

// Kurang lalu simpan
x -= 3;
console.log("Setelah x -= 3:", x);

// Kali lalu simpan
x *= 2;
console.log("Setelah x *= 2:", x);

// Bagi lalu simpan
x /= 4;
console.log("Setelah x /= 4:", x);

// Modulus lalu simpan
x %= 4;
console.log("Setelah x %= 4:", x);
