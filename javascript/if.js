// 6. If Statement
let hour = 9;
let greeting;

// if akan berjalan, jika kondisinya true
if (hour < 10) {
    greeting = "Good Morning";
    console.log(greeting);
} else if (hour < 20) {
    greeting = "Good Day";
    console.log(greeting);
} else {
    greeting = "Good Evening";
    console.log(greeting);
}