// 4. Operator Perbandingan
const a = 10;
const b = "10";
const c = 5;

console.log("a == b:", a == b); //true
console.log("a === b:", a === b); //false

console.log("a != b:", a != b); //false
console.log("a !== b:", a !== b); //true

console.log("a > c:", a > c); //true
console.log("a < c:", a < c); //false
console.log("a >= 10:", a >= 10); //true
console.log("c <= 5:", c <= 5); //true
